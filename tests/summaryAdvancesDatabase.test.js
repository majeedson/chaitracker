after(async()=>db?.close());beforeEach(async()=>{await db.exec('begin');await actor();});afterEach(async()=>db.exec('rollback'));

test('a manager records their own cash advance; it is flagged and reduces expected cash',async()=>{
 const saved=await save(today);assert.equal(Number(saved.expected_cash),15000);
 const advance=await record(today,1,1500,'Cash');
 assert.equal(advance.status,'PAID');assert.equal(advance.source,'SUMMARY');assert.equal(advance.self_recorded,true);assert.equal(advance.installments,1);
 const [summary]=await rows("select expected_cash,short_excess from daily_summaries where id=$1",['SUM-1-'+today]);
 assert.equal(Number(summary.expected_cash),13500);assert.equal(Number(summary.short_excess),500);
 const other=await record(today,2,700,'UPI');assert.equal(other.self_recorded,false);
 assert.equal(Number((await rows("select expected_cash from daily_summaries where id=$1",['SUM-1-'+today]))[0].expected_cash),13500,'UPI advances do not touch the drawer');
});

test('summary advances flow into payroll as advance due',async()=>{
 const advance=await record(today,2,2400,'Cash');await actor();
 const due=await rows('select * from private.advance_due(2,private.salary_period_containing($1::date,$2::date))',[today,'2025-01-07']);
 assert.equal(due.length,1);assert.equal(due[0].advance_id,advance.id);assert.equal(Number(due[0].due),2400);
});

test('business-day window: no future days, managers 7 days back, owner any day',async()=>{
 await assert.rejects(record(day(1)),/future business day/);
 await assert.rejects(record(day(-8)),/last 7 days/);
 await assert.rejects(save(day(-8)),/last 7 days/);
 await assert.rejects(save(day(1)),/future business day/);
 assert.equal((await record(day(-7))).business_date,day(-7));
 assert.equal((await record(day(-40),2,500,'Cash',admin)).business_date,day(-40));
 assert.equal((await save(day(-40),admin)).business_date.toISOString().slice(0,10),day(-40));
});

test('every save writes an audit row, and late entries are marked',async()=>{
 await save(day(-2));await save(day(-2),manager,",p_expenses=>'[{\"category\":\"Petrol\",\"amount\":100,\"mode\":\"Cash\"}]'::jsonb");
 const audit=await rows("select action,details from daily_summary_audit where summary_id=$1 order by id",['SUM-1-'+day(-2)]);
 assert.equal(audit.length,2);assert.ok(audit.every(a=>a.action==='SAVED'&&a.details.late_entry===true));
 assert.equal(audit[0].details.new,true);assert.equal(audit[1].details.new,false);assert.equal(audit[1].details.expenses,1);
 await save(today);assert.equal((await rows("select details from daily_summary_audit where summary_id=$1",['SUM-1-'+today]))[0].details.late_entry,false);
});

test('voiding restores expected cash and is blocked once payroll has used the advance',async()=>{
 await save(today);const advance=await record(today,2,1000,'Cash');
 const voided=(await rows('select void_summary_advance($1,$2) value',[advance.id,'typo']))[0].value;assert.equal(voided.status,'VOID');
 assert.equal(Number((await rows("select expected_cash from daily_summaries where id=$1",['SUM-1-'+today]))[0].expected_cash),15000);
 await assert.rejects(rows('select void_summary_advance($1)',[advance.id]),/Only advances recorded from the Daily Summary/);
 const second=await record(today,2,800,'Cash');await actor();
 await db.exec(`insert into salary_records(id,outlet_id,staff_id,period_start,period_end,payroll_status) values('P',1,2,'${day(-20)}','${day(10)}','FINALIZED')`);
 await actor(manager);await assert.rejects(rows('select void_summary_advance($1)',[second.id]),/already finalised/);
});

test('staff requests cannot be voided from the summary, and closed days are refused',async()=>{
 await actor();await db.exec(`insert into staff_advance_requests(id,staff_id,outlet_id,amount,installments,status,requested_by) values('00000000-0000-0000-0000-0000000000aa',2,1,500,1,'APPROVED','${manager}')`);
 await actor(manager);await assert.rejects(rows("select void_summary_advance('00000000-0000-0000-0000-0000000000aa')"),/Only advances recorded/);
 await save(day(-1));await actor();await db.exec(`update daily_summaries set is_closed=true where id='SUM-1-${day(-1)}'`);
 await assert.rejects(record(day(-1)),/closed/);
});

